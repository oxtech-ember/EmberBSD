#ifndef _DEV_I2C_BRCMSTB_I2CREG_H_
#define _DEV_I2C_BRCMSTB_I2CREG_H_

#define BRCMSTB_I2C_ADDRESS	0x00
#define BRCMSTB_I2C_DATA_IN(n)	(0x04 + 4 * (n))
#define BRCMSTB_I2C_COUNT	0x24
#define BRCMSTB_I2C_CTL		0x28
#define BRCMSTB_I2C_ENABLE	0x2c
#define BRCMSTB_I2C_DATA_OUT(n)	(0x30 + 4 * (n))
#define BRCMSTB_I2C_CTLHI	0x50

#define BRCMSTB_I2C_DTF		0x03
#define BRCMSTB_I2C_READ		0x01
#define BRCMSTB_I2C_SPEED	0xb0
#define BRCMSTB_I2C_97500	0x90
#define BRCMSTB_I2C_INT_EN	0x40
#define BRCMSTB_I2C_RESTART	0x40
#define BRCMSTB_I2C_NOSTART	0x20
#define BRCMSTB_I2C_NOSTOP	0x10
#define BRCMSTB_I2C_NOACK	0x04
#define BRCMSTB_I2C_INTRP	0x02
#define BRCMSTB_I2C_START	0x01
#define BRCMSTB_I2C_DATA4	0x40
#define BRCMSTB_I2C_IGNORE_ACK	0x02
#define BRCMSTB_I2C_COUNT_MASK	0x3f
#define BRCMSTB_I2C_ENABLE_MASK	0x77
#define BRCMSTB_I2C_CTL_MASK	0xf3

#endif /* _DEV_I2C_BRCMSTB_I2CREG_H_ */
