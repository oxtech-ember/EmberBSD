# Origin: EmberBSD, AI-assisted. efidrm nonblocking commit tail contract.
#
# The contract takes the actual source of these functions:
#  - commit_tail() and drm_atomic_helper_commit_tail() of the DRM 5.6 core;
#  - efidrm_crtc_atomic_flush() and efidrm_atomic_commit() of efidrm;
#  - the atomic_commit_tail hook of efidrm, when efidrm_drm_init() sets
#    dev->mode_config.helper_private.
# It compiles them with efidrm-commit-tail-contract.c, which models the
# ordered system_unbound_wq of NetBSD, the software vblank of efidrm and the
# EBUSY rule of drm_atomic_helper_setup_commit().
import argparse
import os
from pathlib import Path
import re
import shlex
import subprocess
import sys
import tempfile
sys.dont_write_bytecode = True


def function(text, head, what):
    """Return the definition that starts with head, up to its closing brace."""
    start = text.find(head)
    if start < 0:
        raise SystemExit(f"FAIL: {what}: no {head!r}")
    end = text.find("\n}\n", start)
    if end < 0:
        raise SystemExit(f"FAIL: {what}: no end of {head!r}")
    return text[start:end + 3]


def efidrm_tail(text):
    """Return the hook table and the tail of efidrm, or None if efidrm has none."""
    init = function(text, "static int\nefidrm_drm_init(", "efidrm.c")
    m = re.search(r"dev->mode_config\.helper_private\s*=\s*&(\w+);", init)
    if m is None:
        return None
    table_name = m.group(1)
    t = re.search(r"static const struct drm_mode_config_helper_funcs\s+" +
                  table_name + r"\s*=\s*\{.*?\n\};\n", text, re.S)
    if t is None:
        raise SystemExit(f"FAIL: efidrm.c: no table {table_name}")
    table = t.group(0)
    f = re.search(r"\.atomic_commit_tail\s*=\s*(\w+)\s*,", table)
    if f is None:
        raise SystemExit(f"FAIL: efidrm.c: {table_name} has no atomic_commit_tail")
    tail = function(text, "static void\n" + f.group(1) + "(", "efidrm.c")
    return tail + "\n" + table + "\n#define EFIDRM_MODE_HELPERS (&" + \
        table_name + ")\n"


def main():
    tools = Path(__file__).resolve().parent
    root = tools.parents[1]
    parser = argparse.ArgumentParser()
    parser.add_argument("--efidrm", type=Path,
        default=root / "sys/external/bsd/drm2/efidrm/efidrm.c")
    parser.add_argument("--helper", type=Path,
        default=root / "sys/external/bsd/drm2/dist/drm/drm_atomic_helper.c")
    parser.add_argument("--cc", default=os.environ.get("CC", "cc"))
    parser.add_argument("--work-dir", type=Path)
    args = parser.parse_args()

    efidrm = args.efidrm.read_text()
    helper = args.helper.read_text()
    parts = [
        "/* Generated by efidrm-commit-tail-contract.py from the actual source. */",
        function(helper, "void drm_atomic_helper_commit_tail(struct drm_atomic_state *old_state)\n{",
                 "drm_atomic_helper.c"),
        function(efidrm, "static void\nefidrm_crtc_atomic_flush(", "efidrm.c"),
        function(efidrm, "static int\nefidrm_atomic_commit(", "efidrm.c"),
    ]
    tail = efidrm_tail(efidrm)
    if tail is None:
        parts.append("/* efidrm sets no helper_private: commit_tail() uses the default. */\n"
                     "#define EFIDRM_MODE_HELPERS NULL\n")
    else:
        parts.append(tail)
    parts.append("static void\nmodel_set_helpers(struct drm_device *dev)\n{\n"
                 "\tdev->mode_config.helper_private = EFIDRM_MODE_HELPERS;\n}\n")
    parts.append(function(helper, "static void commit_tail(struct drm_atomic_state *old_state)\n{",
                          "drm_atomic_helper.c"))

    with tempfile.TemporaryDirectory(prefix="efidrm-commit-tail-") as tmp:
        work = args.work_dir or Path(tmp)
        work.mkdir(parents=True, exist_ok=True)
        (work / "efidrm-commit-tail-extract.c").write_text("\n".join(parts))
        command = (shlex.split(args.cc) +
            ["-std=c11", "-Wall", "-Wextra", "-Werror",
             "-Wno-unused-parameter"] +
            shlex.split(os.environ.get("CFLAGS", "")) +
            ["-I" + str(work), str(tools / "efidrm-commit-tail-contract.c"),
             "-o", str(work / "efidrm-commit-tail-contract")])
        subprocess.run(command, check=True)
        run = subprocess.run(shlex.split(os.environ.get("TEST_RUNNER", "")) +
                             [str(work / "efidrm-commit-tail-contract")])
        if run.returncode != 0:
            sys.exit(run.returncode)


if __name__ == "__main__":
    main()
