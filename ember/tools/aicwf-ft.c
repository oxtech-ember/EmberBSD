#define	ROTR(x, n)	(((x) >> (n)) | ((x) << (32 - (n))))

static void
sha256_block(struct sha256_ctx *c, const uint8_t *p)
{
	uint32_t w[64], a, b, cc, d, e, f, g, h;
	uint32_t t1, t2;
	int i;

	for (i = 0; i < 16; i++)
		w[i] = (uint32_t)p[i * 4] << 24 | (uint32_t)p[i * 4 + 1] << 16 |
		    (uint32_t)p[i * 4 + 2] << 8 | p[i * 4 + 3];
	for (; i < 64; i++) {
		const uint32_t s0 = ROTR(w[i - 15], 7) ^ ROTR(w[i - 15], 18) ^
		    w[i - 15] >> 3;
		const uint32_t s1 = ROTR(w[i - 2], 17) ^ ROTR(w[i - 2], 19) ^
		    w[i - 2] >> 10;

		w[i] = w[i - 16] + s0 + w[i - 7] + s1;
	}
	a = c->h[0]; b = c->h[1]; cc = c->h[2]; d = c->h[3];
	e = c->h[4]; f = c->h[5]; g = c->h[6]; h = c->h[7];
	for (i = 0; i < 64; i++) {
		const uint32_t S1 = ROTR(e, 6) ^ ROTR(e, 11) ^ ROTR(e, 25);
		const uint32_t ch = (e & f) ^ (~e & g);
		const uint32_t S0 = ROTR(a, 2) ^ ROTR(a, 13) ^ ROTR(a, 22);
		const uint32_t maj = (a & b) ^ (a & cc) ^ (b & cc);

		t1 = h + S1 + ch + sha256_k[i] + w[i];
		t2 = S0 + maj;
		h = g; g = f; f = e; e = d + t1;
		d = cc; cc = b; b = a; a = t1 + t2;
	}
	c->h[0] += a; c->h[1] += b; c->h[2] += cc; c->h[3] += d;
	c->h[4] += e; c->h[5] += f; c->h[6] += g; c->h[7] += h;
}

static void
sha256_init(struct sha256_ctx *c)
{
	static const uint32_t init[8] = { 0x6a09e667, 0xbb67ae85, 0x3c6ef372,
	    0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19 };

	memcpy(c->h, init, sizeof(init));
	c->len = 0;
	c->fill = 0;
}

static void
sha256_update(struct sha256_ctx *c, const void *data, size_t len)
{
	const uint8_t *p = data;

	c->len += len;
	while (len > 0) {
		const size_t take = 64 - c->fill < len ? 64 - c->fill : len;

		memcpy(c->buf + c->fill, p, take);
		c->fill += take;
		p += take;
		len -= take;
		if (c->fill == 64) {
			sha256_block(c, c->buf);
			c->fill = 0;
		}
	}
}

static void
sha256_final(struct sha256_ctx *c, uint8_t out[32])
{
	const uint64_t bits = c->len * 8;
	uint8_t pad = 0x80;
	int i;

	sha256_update(c, &pad, 1);
	pad = 0;
	while (c->fill != 56)
		sha256_update(c, &pad, 1);
	for (i = 7; i >= 0; i--)
		sha256_update(c, &(uint8_t){ (uint8_t)(bits >> (i * 8)) }, 1);
	for (i = 0; i < 8; i++) {
		out[i * 4] = c->h[i] >> 24;
		out[i * 4 + 1] = c->h[i] >> 16;
		out[i * 4 + 2] = c->h[i] >> 8;
		out[i * 4 + 3] = c->h[i];
	}
}

static void
sha256(const void *data, size_t len, uint8_t out[32])
{
	struct sha256_ctx c;

	sha256_init(&c);
	sha256_update(&c, data, len);
	sha256_final(&c, out);
}

static void
hmac_sha256(const uint8_t *key, size_t key_len, const void *data, size_t len,
    uint8_t out[32])
{
	uint8_t k[64], ipad[64], opad[64], t[32];
	struct sha256_ctx c;
	size_t i;

	memset(k, 0, sizeof(k));
	if (key_len > 64) {
		sha256(key, key_len, k);
	} else
		memcpy(k, key, key_len);
	for (i = 0; i < 64; i++) {
		ipad[i] = k[i] ^ 0x36;
		opad[i] = k[i] ^ 0x5c;
	}
	sha256_init(&c);
	sha256_update(&c, ipad, 64);
	sha256_update(&c, data, len);
	sha256_final(&c, t);
	sha256_init(&c);
	sha256_update(&c, opad, 64);
	sha256_update(&c, t, 32);
	sha256_final(&c, out);
}

/* The 802.11 KDF: T(i) = HMAC(K, i || label || context || bits16le). */
static void
dot11_kdf(const uint8_t *key, size_t key_len, const char *label,
    const uint8_t *context, size_t ctx_len, size_t out_bytes, uint8_t *out)
{
	const size_t bits = out_bytes * 8;
	const size_t blocks = (bits + 255) / 256;
	const size_t label_len = strlen(label);
	uint8_t block[32];
	size_t done = 0;
	uint8_t input[512];
	uint8_t i;

	assert(label_len + ctx_len + 3 <= sizeof(input));
	for (i = 1; i <= blocks; i++) {
		size_t pos = 0;

		input[pos++] = i;
		memcpy(input + pos, label, label_len);
		pos += label_len;
		memcpy(input + pos, context, ctx_len);
		pos += ctx_len;
		input[pos++] = bits & 0xff;
		input[pos++] = bits >> 8;
		hmac_sha256(key, key_len, input, pos, block);
		memcpy(out + done, block,
		    done + 32 > out_bytes ? out_bytes - done : 32);
		done += 32;
	}
}

static void
ft_derive_r0(const uint8_t xxkey[32], const uint8_t *ssid, size_t ssid_len,
    uint16_t mdid, const uint8_t *r0kh, size_t r0kh_len,
    const uint8_t s0kh[6], uint8_t pmk_r0[32], uint8_t salt[16])
{
	uint8_t context[128], key_data[48];
	size_t pos = 0;

	assert(ssid_len <= 32 && r0kh_len <= 48 && 1 + ssid_len + 2 +
	    1 + r0kh_len + 6 <= sizeof(context));
	context[pos++] = (uint8_t)ssid_len;
	memcpy(context + pos, ssid, ssid_len);
	pos += ssid_len;
	context[pos++] = mdid & 0xff;
	context[pos++] = mdid >> 8;
	context[pos++] = (uint8_t)r0kh_len;
	memcpy(context + pos, r0kh, r0kh_len);
	pos += r0kh_len;
	memcpy(context + pos, s0kh, 6);
	pos += 6;
	dot11_kdf(xxkey, 32, "FT-R0", context, pos, 48, key_data);
	memcpy(pmk_r0, key_data, 32);
	memcpy(salt, key_data + 32, 16);
}

static void
ft_name_r0(const uint8_t pmk_r0[32], const uint8_t salt[16],
    uint8_t name[16])
{
	uint8_t input[6 + 32 + 16];

	memcpy(input, "FT-R0N", 6);
	memcpy(input + 6, pmk_r0, 32);
	memcpy(input + 6 + 32, salt, 16);
	sha256(input, sizeof(input), input);
	memcpy(name, input, 16);
}

static void
ft_derive_r1(const uint8_t pmk_r0[32], const uint8_t r1kh[6],
    const uint8_t s1kh[6], uint8_t pmk_r1[32])
{
	uint8_t context[12];

	memcpy(context, r1kh, 6);
	memcpy(context + 6, s1kh, 6);
	dot11_kdf(pmk_r0, 32, "FT-R1", context, sizeof(context), 32, pmk_r1);
}

static void
ft_name_r1(const uint8_t r0_name[16], const uint8_t pmk_r1[32],
    uint8_t name[16])
{
	uint8_t input[6 + 16 + 32], digest[32];

	memcpy(input, "FT-R1N", 6);
	memcpy(input + 6, r0_name, 16);
	memcpy(input + 6 + 16, pmk_r1, 32);
	sha256(input, sizeof(input), digest);
	memcpy(name, digest, 16);
}

static const uint8_t vec_xxkey[32] = {
	0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0a,0x0b,0x0c,0x0d,
	0x0e,0x0f,0x10,0x11,0x12,0x13,0x14,0x15,0x16,0x17,0x18,0x19,0x1a,0x1b,
	0x1c,0x1d,0x1e,0x1f
};
static const uint8_t vec_ssid[] = "SmolevWi-Fi";
static const uint8_t vec_r0kh[6] = { 0x5a,0xff,0x20,0x8b,0x0a,0x01 };
static const uint8_t vec_s0kh[6] = { 0xb4,0x65,0xdc,0x2d,0x8d,0xa7 };
static const uint8_t vec_r1kh[6] = { 0x5a,0xff,0x20,0x8b,0x1f,0x42 };

int
main(void)
{
	uint8_t r0[32], salt[16], n0[16], r1[32], n1[16];
	unsigned checks = 0;
	uint8_t sha_out[32];

	/* FIPS 180-2 vector: abc. */
	static const uint8_t abc_digest[32] = {
		0xba,0x78,0x16,0xbf,0x8f,0x01,0xcf,0xea,0x41,0x41,0x40,0xde,
		0x5d,0xae,0x22,0x23,0xb0,0x03,0x61,0xa3,0x96,0x17,0x7a,0x9c,
		0xb4,0x10,0xff,0x61,0xf2,0x00,0x15,0xad
	};

	sha256("abc", 3, sha_out);
	assert(memcmp(sha_out, abc_digest, 32) == 0);
	checks++;

	/* RFC 4231 test case 2 for HMAC-SHA256. */
	static const uint8_t hm_key[] = "Jefe";
	static const uint8_t hm_data[] = "what do ya want for nothing?";
	static const uint8_t hm_out[32] = {
		0x5b,0xdc,0xc1,0x46,0xbf,0x60,0x75,0x4e,0x6a,0x04,0x24,0x26,
		0x08,0x95,0x75,0xc7,0x5a,0x00,0x3f,0x08,0x9d,0x27,0x39,0x83,
		0x9d,0xec,0x58,0xb9,0x64,0xec,0x38,0x43
	};

	hmac_sha256(hm_key, sizeof(hm_key) - 1, hm_data, sizeof(hm_data) - 1,
	    sha_out);
	assert(memcmp(sha_out, hm_out, 32) == 0);
	checks++;

	/* FT hierarchy vectors, generated by an independent implementation. */
	ft_derive_r0(vec_xxkey, vec_ssid, sizeof(vec_ssid) - 1, 0x5811,
	    vec_r0kh, sizeof(vec_r0kh), vec_s0kh, r0, salt);
	assert(memcmp(r0,
	    "\x2d\x73\x84\xb7\xa6\x89\xd4\x78\x8b\x53\x98\xa2\x12\x96\x72\x54\x78\x29\x8c\xe8\xc3\x6f\x85\x2d\x99\xa1\x60\x2e\x67\x18\x65\xad",
	    32) == 0);
	assert(memcmp(salt,
	    "\x4f\x0d\xb7\x51\xd3\x1a\x88\x8f\x4e\xa6\x7f\x67\xfc\xc9\xa9\x00",
	    16) == 0);
	checks += 2;
	ft_name_r0(r0, salt, n0);
	assert(memcmp(n0,
	    "\xc2\xa4\xb7\xf1\x31\x52\x1e\x13\xf1\xea\x84\xab\xc9\x4a\x22\xfc",
	    16) == 0);
	checks++;
	ft_derive_r1(r0, vec_r1kh, vec_s0kh, r1);
	assert(memcmp(r1,
	    "\x75\xf9\x96\x7c\x1c\x13\xba\x35\x1e\x8b\x1a\x3a\xca\x49\x6e\xab\x8f\x05\xaf\x26\xc4\x09\x92\x59\x09\x0e\x07\x95\xf5\x05\xd0\xb7",
	    32) == 0);
	checks++;
	ft_name_r1(n0, r1, n1);
	assert(memcmp(n1,
	    "\x2a\xfb\x99\x7e\xa7\xbb\x6d\x58\xe4\x4c\xeb\x85\x17\x43\xd4\x06",
	    16) == 0);
	checks++;

	/* A one-octet label-length context also passes through the KDF
	 * unchanged in the block counter; length must round up blocks. */
	uint8_t big[64];

	dot11_kdf(vec_xxkey, 32, "FT-R0", (const uint8_t *)"", 0, 64, big);
	assert(big[31] != big[32]);
	checks++;

	printf("PASS: %u FT hierarchy checks (FIPS, RFC 4231, cross-vectors)\n",
	    checks);
	return 0;
}
