require 'open3'
require 'tmpdir'
root = File.expand_path('../..', __dir__)
Dir.mktmpdir('ember-logo') do |dir|
  pixels = File.join(dir, 'logo.rgb')
  _, err, result = Open3.capture3('magick', File.join(root, 'ember/branding/emberbsd-logo.png'),
    '-resize', '48x54!', '-background', 'black', '-alpha', 'remove', '-alpha', 'off',
    '+dither', '-colors', '16', '-depth', '8', "RGB:#{pixels}")
  abort err unless result.success?
  data = File.binread(pixels).bytes.each_slice(3).to_a
  abort 'invalid image size' unless data.length == 48 * 54
  palette = data.uniq
  abort 'palette too large' if palette.length > 16
  palette_data = "static const uint8_t ember_logo_palette[][3] = {\n" +
    palette.map { |rgb| "\t{ #{rgb.join(', ')} }," }.join("\n") + "\n};"
  pixel_data = "static const uint8_t ember_logo_pixels[] = {\n" +
    data.map { |rgb| palette.index(rgb) }.each_slice(24).map { |row| "\t#{row.join(', ')}," }.join("\n") + "\n};"
  output = <<~C
/* Origin: EmberBSD flame mascot, from ember/branding/emberbsd-logo.png, 2026-10-13. */
/* SPDX-License-Identifier: BSD-2-Clause */
/* Generated by ember/tools/boot-logo.rb. */
#ifndef EMBER_BOOT_LOGO_H
#define EMBER_BOOT_LOGO_H
#ifdef _STANDALONE
#include <sys/stdbool.h>
#include <sys/stdint.h>
#else
#include <stdbool.h>
#include <stdint.h>
#endif
#define EMBER_LOGO_WIDTH 48
#define EMBER_LOGO_HEIGHT 54
#define EMBER_LOGO_TEXT_ROW 8
#{palette_data}\n#{pixel_data}

static inline bool
ember_logo_origin(unsigned width, unsigned height, unsigned cols,
    unsigned rows, unsigned *x, unsigned *y)
{

	if (width < 800 || height < 600 || cols < 80 || rows < 25)
		return false;
	*x = width - EMBER_LOGO_WIDTH - 16;
	*y = 8;
	return true;
}
#endif
C
  if ARGV == ['--check']
    abort 'logo header differs' unless output == File.read(File.join(root, 'sys/arch/i386/stand/efiboot/ember_logo.h'))
  elsif ARGV.empty?
    File.write(File.join(root, 'sys/arch/i386/stand/efiboot/ember_logo.h'), output)
  else
    abort 'Usage: ruby ember/tools/boot-logo.rb [--check]'
  end
end
