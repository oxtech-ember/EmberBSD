# Origin: EmberBSD console mascot traced from its flame logo, 2026-10-13.
# SPDX-License-Identifier: BSD-2-Clause
require 'json'
require 'digest'
require 'open3'
root = File.expand_path('../..', __dir__)
asset = File.join(root, 'ember/branding/emberbsd-logo.png')
output = File.join(root, 'sys/lib/libsa/ember_boot_logo.h')
data_output = File.join(root, 'sys/lib/libsa/ember_logo_data.h')
raw, error, status = Open3.capture3('magick', asset, '-resize', '27x14!',
  '-alpha', 'on', '-depth', '8', 'rgba:-')
abort error unless status.success?
pixels = raw.bytes.each_slice(4).to_a
abort 'unexpected logo dimensions' unless pixels.size == 27 * 14
rows = 14.times.map do |y|
  27.times.map do |x|
    r, g, b, a = pixels[y * 27 + x]
    if a < 100 || [r, g, b].max < 45 || (r < 160 && g < 100)
      ' '
    elsif g < 85
      'r'
    elsif g < 160
      '+'
    else
      '#'
    end
  end.join
end
# Preserve the dark face, paired capsule eyes and smile at console resolution.
rows[8][9, 4] = ' ' * 4
rows[8][17, 4] = ' ' * 4
rows[9][7, 15] = ' ' * 15
rows[10][8, 14] = ' ' * 14
rows[11][9, 11] = ' ' * 11
[9, 10].each do |y|
  rows[y][10, 2] = '||'
  rows[y][18, 2] = '||'
end
rows[10][14, 3] = '\\_/'
rows.pop while rows.last.strip.empty?
abort 'mascot exceeds its console budget' unless rows.size <= 13
letters = {
  'E'=>['#####','#    ','#    ','#### ','#    ','#    ','#####'],
  'M'=>['#   #','## ##','# # #','#   #','#   #','#   #','#   #'],
  'B'=>['#### ','#   #','#   #','#### ','#   #','#   #','#### '],
  'R'=>['#### ','#   #','#   #','#### ','# #  ','#  # ','#   #'],
  'S'=>[' ####','#    ','#    ',' ### ','    #','    #','#### '],
  'D'=>['#### ','#   #','#   #','#   #','#   #','#   #','#### ']
}
wordmark = 7.times.map { |i| 'EMBERBSD'.chars.map { |c| letters.fetch(c)[i] }.join(' ') }
header = <<~HEAD
/* Origin: EmberBSD console mascot, 2026-10-13. */
/* SPDX-License-Identifier: BSD-2-Clause */
/* Generated by ember/tools/boot-logo.rb. */
/* Source PNG SHA256: #{Digest::SHA256.file(asset).hexdigest} */
#ifndef _LIBSA_EMBER_BOOT_LOGO_H
#define _LIBSA_EMBER_BOOT_LOGO_H

/* Palette letters select console attributes; all rendered glyphs are ASCII. */
#include "ember_logo_data.h"
static inline void
ember_boot_logo(void (*color)(int))
{
HEAD
header += <<~TAIL
\tunsigned i, j;
\tint event, last = -1;
\tchar cell, glyph;

\tif (color != NULL)
\t\tcolor(BOOTCFG_COLOR_SAVE);
\tfor (i = 0; i < sizeof(ember_logo_mascot) / sizeof(ember_logo_mascot[0]); i++) {
\t\tfor (j = 0; ember_logo_mascot[i][j] != '\\0'; j++) {
\t\t\tcell = ember_logo_mascot[i][j];
\t\t\tif (cell == ' ') {
\t\t\t\tputchar(' ');
\t\t\t\tcontinue;
\t\t\t}
\t\t\tglyph = '#';
\t\t\tswitch (cell) {
\t\t\tcase 'r':
\t\t\t\tevent = BOOTCFG_COLOR_OUTER;
\t\t\t\tbreak;
\t\t\tcase '+':
\t\t\t\tevent = BOOTCFG_COLOR_INNER;
\t\t\t\tbreak;
\t\t\tcase '#':
\t\t\t\tevent = BOOTCFG_COLOR_FLAME;
\t\t\t\tbreak;
\t\t\tdefault:
\t\t\t\tevent = BOOTCFG_COLOR_WORDMARK;
\t\t\t\tglyph = cell;
\t\t\t\tbreak;
\t\t\t}
\t\t\tif (color != NULL && event != last)
\t\t\t\tcolor(event);
\t\t\tlast = event;
\t\t\tputchar(glyph);
\t\t}
\t\tif (color != NULL && last != BOOTCFG_COLOR_WORDMARK)
\t\t\tcolor(BOOTCFG_COLOR_WORDMARK);
\t\tlast = BOOTCFG_COLOR_WORDMARK;
\t\tprintf("  %s\\n", (i >= 4 && i < 11) ? ember_logo_wordmark[i - 4] : "");
\t}
\tif (color != NULL)
\t\tcolor(BOOTCFG_COLOR_RESTORE);
\tprintf("\\n");
}

#endif /* _LIBSA_EMBER_BOOT_LOGO_H */
TAIL
data = "/* Origin: EmberBSD shared console logo data, 2026-10-13. */\n/* SPDX-License-Identifier: BSD-2-Clause */\n/* Generated by ember/tools/boot-logo.rb. */\n#ifndef _LIBSA_EMBER_LOGO_DATA_H\n#define _LIBSA_EMBER_LOGO_DATA_H\n"
data += "static const char * const ember_logo_mascot[] = {\n"
data += rows.map { |r| "\t#{JSON.generate(r)},\n" }.join
data += "};\nstatic const char * const ember_logo_wordmark[] = {\n"
data += wordmark.map { |r| "\t#{JSON.generate(r)},\n" }.join
data += "};\n#endif\n"
if ARGV == ['--check']
  abort 'generated console mascot differs' unless File.binread(output) == header
  abort 'shared console logo differs' unless File.binread(data_output) == data
  puts 'PASS: console mascot matches its source logo and facial accents'
elsif ARGV.empty?
  File.write(output, header)
  File.write(data_output, data)
else
  abort 'Usage: ruby ember/tools/boot-logo.rb [--check]'
end
