#include <inttypes.h>
#include <stdio.h>
#include <stdlib.h>
#include "broadcom/common/v3d_device_info.h"
#include "broadcom/qpu/qpu_instr.h"
#include "broadcom/qpu/qpu_disasm.h"
#include "util/ralloc.h"

static const struct v3d_device_info dev = {.ver=71, .rev=10};
static struct v3d_qpu_instr
nop(void)
{
	return (struct v3d_qpu_instr){.type=V3D_QPU_INSTR_TYPE_ALU,
	    .alu={.add={.op=V3D_QPU_A_NOP,.waddr=V3D_QPU_WADDR_NOP,.magic_write=true},
	    .mul={.op=V3D_QPU_M_NOP,.waddr=V3D_QPU_WADDR_NOP,.magic_write=true}}};
}

int
main(void)
{
	struct v3d_qpu_instr p[15], decoded;
	uint64_t word, again;
	for(unsigned i=0;i<15;i++)p[i]=nop();
	p[0].sig.ldunifrf=true; p[0].sig_addr=0; /* Output GPU address. */
	p[1].sig.ldunifrf=true; p[1].sig_addr=1; /* Changing integer seed. */
	p[2].alu.add.op=V3D_QPU_A_EIDX;
	p[2].alu.add.waddr=2; p[2].alu.add.magic_write=false;
	p[3].alu.add.op=V3D_QPU_A_ADD;
	p[3].alu.add.waddr=3; p[3].alu.add.magic_write=false;
	p[3].alu.add.a.raddr=1; p[3].alu.add.b.raddr=2;
	p[4].alu.add.op=V3D_QPU_A_SHL;
	p[4].alu.add.waddr=4; p[4].alu.add.magic_write=false;
	p[4].alu.add.a.raddr=2; p[4].alu.add.b.raddr=2;
	p[4].sig.small_imm_b=true;
	p[5].alu.add.op=V3D_QPU_A_MOV;
	p[5].alu.add.waddr=V3D_QPU_WADDR_TMUD; p[5].alu.add.a.raddr=3;
	p[6].alu.add.op=V3D_QPU_A_ADD;
	p[6].alu.add.waddr=V3D_QPU_WADDR_TMUA;
	p[6].alu.add.a.raddr=0; p[6].alu.add.b.raddr=4;
	p[7].sig.thrsw=true; p[8].sig.thrsw=true;
	p[10].alu.add.op=V3D_QPU_A_TMUWT;
	p[12].sig.thrsw=true;
	puts("/* Generated by bcm2712-v3d-csd-shader.c with Mesa 26.2.4. */");
	puts("static const uint64_t csd_shader[] = {");
	for(unsigned i=0;i<15;i++) {
		if(!v3d_qpu_instr_pack(&dev,&p[i],&word) ||
		    !v3d_qpu_instr_unpack(&dev,word,&decoded) ||
		    !v3d_qpu_instr_pack(&dev,&decoded,&again) || again!=word)
			return 1;
		const char *text=v3d_qpu_disasm(&dev,word);
		printf("\tUINT64_C(0x%016" PRIx64 "), /* %s */\n",word,text);
		ralloc_free((void *)text);
	}
	puts("};");
	return 0;
}
